class Command(BaseCommand):
    help = 'Load sample medicine data (23 categories, 100+ medicines each)'

    def add_arguments(self, parser):
        parser.add_argument('--clear', action='store_true', help='Clear existing medicines first')

    def handle(self, *args, **options):
        if options['clear']:
            Medicine.objects.all().delete()
            self.stdout.write('Cleared existing medicines.')

        created = 0
        skipped = 0
        for m in MEDICINES:
            _, was_created = Medicine.objects.get_or_create(
                name=m['name'],
                defaults={
                    'generic_name': m['generic'],
                    'unit': m['unit'],
                    'category': m['cat'],
                    'unit_price': m['price'],
                    'stock_quantity': m['stock'],
                    'minimum_stock': max(10, m['stock'] // 10),
                    'is_active': True,
                }
            )
            if was_created:
                created += 1
            else:
                skipped += 1

        self.stdout.write(self.style.SUCCESS(
            f'Done. Created: {created} medicines, Skipped (already exist): {skipped}. '
            f'Total medicines: {Medicine.objects.count()}'
        ))
